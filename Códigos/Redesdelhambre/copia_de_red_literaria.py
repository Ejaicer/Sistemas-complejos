##### personajes sinsajo
#personajes = ["Katniss", "Peeta", "Gale", "Coin", "Snow", "Haymitch", "Finnick", "Beetee", "Johanna", "Annie", "Enobaria", "Boggs", "Plutarch", "Cressida", "Messalla", "Castor", "Pollux", "Effie", "Prim", "Madre", "Hazelle", "Posy", "Vick", "Rory", "Buttercup", "Lyme", "Paylor", "Jackson", "Homes", "Mitchell", "Leeg", "Caesar", "Tigris", "Aurelius", "Delly","Fulvia"]
# Número máximo de palabras entre dos nombres para considerar que interactúan.
radio = 15

with open('/content/juegos.txt', 'r', encoding='utf-8') as f:
#with open('/content/enllamas.txt', 'r', encoding='utf-8') as f:
#with open('/content/sinsajo.txt', 'r', encoding='utf-8') as f:
    texto = f.read()

###############################################################

# Verifica los parámetros
if radio < 0:
    raise ValueError("El radio debe ser un entero mayor o igual a 0.")

if len(personajes) != len(set(personajes)):
    raise ValueError("La lista de personajes contiene nombres repetidos.")

# Separa el texto en palabras, ignorando puntuación.
palabras = re.findall(r"\b[\wÁÉÍÓÚÜÑáéíóúüñ]+\b", texto, flags=re.UNICODE)

# Busca cada nombre como una secuencia de palabras.
# Así, un nombre compuesto como "María José" cuenta como una sola aparición.
def normalizar(s):
    return s.casefold()

tokens = [normalizar(p) for p in palabras]

apariciones = {personaje: 0 for personaje in personajes}
ocurrencias = []  # Elementos: (posición inicial, posición final, índice del personaje)

for indice_personaje, personaje in enumerate(personajes):
    nombre_tokens = [normalizar(p) for p in re.findall(
        r"\b[\wÁÉÍÓÚÜÑáéíóúüñ]+\b", personaje, flags=re.UNICODE
    )]

    if not nombre_tokens:
        continue

    largo = len(nombre_tokens)

    for inicio in range(len(tokens) - largo + 1):
        if tokens[inicio:inicio + largo] == nombre_tokens:
            fin = inicio + largo - 1
            ocurrencias.append((inicio, fin, indice_personaje))
            apariciones[personaje] += 1

# Ordena las apariciones por su posición en el texto.
ocurrencias.sort(key=lambda x: (x[0], x[1], x[2]))

# Construye la matriz simétrica de interacciones.
n = len(personajes)
matriz = np.zeros((n, n), dtype=int)

for i in range(len(ocurrencias)):
    inicio_a, fin_a, personaje_a = ocurrencias[i]

    for j in range(i + 1, len(ocurrencias)):
        inicio_b, fin_b, personaje_b = ocurrencias[j]

        if personaje_a == personaje_b:
            continue

        # Número de palabras entre ambos nombres.
        # Si los nombres son adyacentes, la distancia es 0.
        distancia = max(0, inicio_b - fin_a - 1)

        if distancia <= radio:
            matriz[personaje_a, personaje_b] += 1
            matriz[personaje_b, personaje_a] += 1

# Presenta los resultados como tablas.
conteo_apariciones = pd.Series(apariciones,name="Apariciones")
conteo_apariciones.index.name = "Personaje"
matriz_interacciones = pd.DataFrame(
    matriz,
    index=personajes,
    columns=personajes
)

print("Apariciones de cada personaje:")
display(conteo_apariciones.to_frame())

print("Matriz pesada de interacciones:")
display(matriz_interacciones)


######################################################## Guarda la matriz de interacciones y la lista de peso de aparicion

