##########################################################

# Escribe los nombres como aparecen en el texto.
#####personajes libro 1
personajes = ["Katniss", "Peeta", "Prim","Snow", "Haymitch","Gale","Effie","Cinna","Portia", "Rue","Cato", "Glimmer", "Comadreja","Madre", "Thresh","Caesar","Sae", "Madge","Claudius","Johanna","Venia","Flavius","Octavia","Titus","Atala","Buttercup"]
